/// Emits the Dart API for a parsed td_api.tl. Output layout is fixed here
/// (no `dart format`), so regenerating is byte-identical on any SDK.
library;

import 'tl.dart';

const _header = '// GENERATED by tool/generate.dart from schema/td_api.tl. Do not edit.\n\n';

/// Pinned TDLib release from schema/VERSION.
final class TdlibVersion {
  const TdlibVersion(this.version, this.commit);

  final String version;
  final String commit;

  factory TdlibVersion.parse(String source) {
    final values = <String, String>{};
    for (final line in source.split('\n')) {
      final i = line.indexOf('=');
      if (i > 0) values[line.substring(0, i).trim()] = line.substring(i + 1).trim();
    }
    final version = values['version'];
    final commit = values['commit'];
    if (version == null || commit == null || !RegExp(r'^[0-9a-f]{40}$').hasMatch(commit)) {
      throw FormatException('schema/VERSION needs version=<x.y.z> and commit=<40 hex digits>', source);
    }
    return TdlibVersion(version, commit);
  }
}

String _cap(String s) => s[0].toUpperCase() + s.substring(1);

String className(String tlName) {
  final name = _cap(tlName);
  return name == 'Error' ? 'TdError' : name;
}

const _generatedMembers = {
  'clientId', 'currentObjectId', 'defaultObjectId', 'copyWith', 'toJson', 'toString', //
  'hashCode', 'runtimeType', 'noSuchMethod',
};

const _dartReserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', 'default', 'do', 'else', //
  'enum', 'extends', 'false', 'final', 'finally', 'for', 'if', 'in', 'is', 'new', 'null', //
  'rethrow', 'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'var', 'void', //
  'while', 'with',
};

String fieldName(String tlName) {
  final parts = tlName.split('_');
  final camel = parts.first + parts.skip(1).where((p) => p.isNotEmpty).map(_cap).join();
  // TdObject.extra is the request tag; a TL field of that name gets another one.
  if (camel == 'extra') return 'extraValue';
  if (_generatedMembers.contains(camel) || _dartReserved.contains(camel)) {
    throw StateError('TL field "$tlName" collides with a Dart keyword or generated member');
  }
  return camel;
}

String fileName(String tlName) => tlName
    .replaceAllMapped(RegExp('[A-Z]'), (m) => '_${m[0]!.toLowerCase()}')
    .replaceFirst(RegExp('^_'), '');

bool _mayBeNull(String doc) {
  final d = doc.toLowerCase();
  return d.contains('may be null') || d.contains('pass null');
}

bool _isObject(TlType t) => !t.isPrimitive && !t.isVector;

/// Object fields documented as nullable; primitives and vectors never are.
bool _nullable(TlField f) => _isObject(f.type) && _mayBeNull(f.doc);

/// `vector<message>` documented with "may be null" entries (getMessages).
bool _nullableElements(TlField f) =>
    f.type.isVector && _isObject(f.type.element!) && f.doc.toLowerCase().contains('may be null');

String _dartType(TlType t, {bool nullableElements = false}) {
  if (t.isVector) return 'List<${_dartType(t.element!)}${nullableElements ? '?' : ''}>';
  return switch (t.name) {
    'int32' || 'int53' || 'int64' => 'int',
    'double' => 'double',
    'string' || 'bytes' => 'String',
    'Bool' => 'bool',
    _ => className(t.name),
  };
}

String _fieldType(TlField f) =>
    '${_dartType(f.type, nullableElements: _nullableElements(f))}${_nullable(f) ? '?' : ''}';

String _decode(TlType t, String v, {bool nullable = false, bool nullableElements = false}) {
  if (t.isVector) {
    return '_list($v, (e) => ${_decode(t.element!, 'e', nullable: nullableElements)})';
  }
  final plain = switch (t.name) {
    'int32' || 'int53' => '_int($v)',
    'int64' => '_int64($v)',
    'double' => '_double($v)',
    'string' || 'bytes' => '_string($v)',
    'Bool' => '_bool($v)',
    _ => '${className(t.name)}.fromJson(_map($v))',
  };
  return nullable && _isObject(t) ? '$v == null ? null : $plain' : plain;
}

String _encode(TlType t, String v, {bool nullable = false, bool nullableElements = false}) {
  if (t.isVector) {
    final e = t.element!;
    if (e.isPrimitive && e.name != 'int64') return v;
    return '$v.map((e) => ${_encode(e, 'e', nullable: nullableElements)}).toList()';
  }
  if (t.name == 'int64') return '$v.toString()';
  if (t.isPrimitive) return v;
  return nullable ? '$v?.toJson()' : '$v.toJson()';
}

String _doc(String text, String indent) {
  final clean = text.replaceAll('<', '&lt;').replaceAll('>', '&gt;').trim();
  return clean.isEmpty ? '' : '$indent/// $clean\n';
}

void _fields(StringBuffer b, TlConstructor c) {
  for (final f in c.fields) {
    b.write(_doc(f.doc, '  '));
    b.writeln('  final ${_fieldType(f)} ${fieldName(f.name)};');
    b.writeln();
  }
}

void _constructorParams(StringBuffer b, TlConstructor c) {
  for (final f in c.fields) {
    b.writeln('    ${_nullable(f) ? '' : 'required '}this.${fieldName(f.name)},');
  }
}

void _jsonFields(StringBuffer b, TlConstructor c) {
  for (final f in c.fields) {
    final value = _encode(f.type, fieldName(f.name), nullable: _nullable(f), nullableElements: _nullableElements(f));
    b.writeln("    '${f.name}': $value,");
  }
}

void _copyWith(StringBuffer b, TlConstructor c, String name, {required bool override, required bool tagged}) {
  if (override) b.writeln('  @override');
  b.writeln('  $name copyWith({');
  for (final f in c.fields) {
    final type = _fieldType(f);
    b.writeln('    ${type.endsWith('?') ? type : '$type?'} ${fieldName(f.name)},');
  }
  if (tagged) {
    b.writeln('    dynamic extra,');
    b.writeln('    int? clientId,');
  }
  b.writeln('  }) => $name(');
  for (final f in c.fields) {
    final n = fieldName(f.name);
    b.writeln('    $n: $n ?? this.$n,');
  }
  if (tagged) {
    b.writeln('    extra: extra ?? this.extra,');
    b.writeln('    clientId: clientId ?? this.clientId,');
  }
  b.writeln('  );');
}

String _objectClass(TlConstructor c, String parent) {
  final name = className(c.name);
  final b = StringBuffer()
    ..write(_doc(c.doc, ''))
    ..writeln('final class $name extends $parent {')
    ..writeln('  const $name({');
  _constructorParams(b, c);
  b
    ..writeln('    this.extra,')
    ..writeln('    this.clientId,')
    ..writeln('  });')
    ..writeln();
  _fields(b, c);
  b
    ..writeln('  @override')
    ..writeln('  final dynamic extra;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  final int? clientId;')
    ..writeln()
    ..writeln("  static const String defaultObjectId = '${c.name}';")
    ..writeln()
    ..writeln('  @override')
    ..writeln('  String get currentObjectId => defaultObjectId;')
    ..writeln()
    ..writeln('  factory $name.fromJson(Map<String, dynamic> json) => $name(');
  for (final f in c.fields) {
    final value = _decode(
      f.type,
      "json['${f.name}']",
      nullable: _nullable(f),
      nullableElements: _nullableElements(f),
    );
    b.writeln('    ${fieldName(f.name)}: $value,');
  }
  b
    ..writeln("    extra: json['@extra'],")
    ..writeln("    clientId: json['@client_id'] as int?,")
    ..writeln('  );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Map<String, dynamic> toJson() => {')
    ..writeln("    '@type': defaultObjectId,");
  _jsonFields(b, c);
  b
    ..writeln('  };')
    ..writeln();
  _copyWith(b, c, name, override: parent != 'TdObject', tagged: true);
  b.writeln('}');
  return b.toString();
}

String _abstractClass(String tlName, String doc, List<TlConstructor> children) {
  final name = className(tlName);
  final b = StringBuffer()
    ..write(_doc(doc, ''))
    ..writeln('sealed class $name extends TdObject {')
    ..writeln('  const $name();')
    ..writeln()
    ..writeln("  static const String defaultObjectId = '${tlName[0].toLowerCase()}${tlName.substring(1)}';")
    ..writeln()
    ..writeln("  factory $name.fromJson(Map<String, dynamic> json) => switch (json['@type']) {");
  for (final c in children) {
    final child = className(c.name);
    b.writeln('    $child.defaultObjectId => $child.fromJson(json),');
  }
  b
    ..writeln("    _ => throw FormatException('Unknown object \${json['@type']} (expected child of $name)', json),")
    ..writeln('  };')
    ..writeln()
    ..writeln('  $name copyWith();')
    ..writeln('}');
  return b.toString();
}

String _functionClass(TlConstructor c) {
  final name = className(c.name);
  final b = StringBuffer()..write(_doc(c.doc, ''));
  b
    ..writeln('///')
    ..writeln('/// Returns [${className(c.result)}].')
    ..writeln('final class $name extends TdFunction {');
  if (c.fields.isEmpty) {
    b.writeln('  const $name();');
  } else {
    b.writeln('  const $name({');
    _constructorParams(b, c);
    b.writeln('  });');
  }
  b.writeln();
  _fields(b, c);
  b
    ..writeln("  static const String defaultObjectId = '${c.name}';")
    ..writeln()
    ..writeln('  @override')
    ..writeln('  String get currentObjectId => defaultObjectId;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Map<String, dynamic> toJson([dynamic extra]) => {')
    ..writeln("    '@type': defaultObjectId,");
  _jsonFields(b, c);
  b
    ..writeln("    '@extra': extra,")
    ..writeln('  };');
  if (c.fields.isNotEmpty) {
    b.writeln();
    _copyWith(b, c, name, override: false, tagged: false);
  }
  b.writeln('}');
  return b.toString();
}

const _objectBase = '''
part of 'tdapi.dart';

/// A TDLib result or update. Parse one with [convertMapToObject].
sealed class TdObject {
  const TdObject();

  /// The `@extra` tag of the request this object answers; null for updates.
  dynamic get extra => null;

  /// The TDLib client that sent this object.
  int? get clientId => null;

  /// TDLib type name, e.g. `updateNewMessage`.
  String get currentObjectId;

  Map<String, dynamic> toJson();

  @override
  String toString() => jsonEncode(toJson());
}

/// A TDLib request; send `toJson(extra)` with `td_send`.
sealed class TdFunction {
  const TdFunction();

  String get currentObjectId;

  Map<String, dynamic> toJson([dynamic extra]);

  @override
  String toString() => jsonEncode(toJson());
}
''';

const _helpers = '''
part of 'tdapi.dart';

int _int(Object? v) => v == null ? 0 : (v as num).toInt();

/// TDLib sends int64 as a JSON string; numbers are accepted too.
int _int64(Object? v) => switch (v) {
  null => 0,
  int() => v,
  String() => int.parse(v),
  num() => v.toInt(),
  _ => throw FormatException('Expected an int64, got \$v'),
};

double _double(Object? v) => v == null ? 0.0 : (v as num).toDouble();

String _string(Object? v) => v == null ? '' : v as String;

bool _bool(Object? v) => v == null ? false : v as bool;

Map<String, dynamic> _map(Object? v) => v as Map<String, dynamic>;

List<T> _list<T>(Object? v, T Function(Object? e) item) =>
    v == null ? <T>[] : <T>[for (final e in v as List) item(e)];
''';

Map<String, String> emitLibrary(TlSchema schema, TdlibVersion version) {
  final abstractDocs = <String, String>{for (final c in schema.classes.values) c.name: c.doc};
  for (final o in schema.objects) {
    if (_cap(o.name) != o.result) abstractDocs.putIfAbsent(o.result, () => '');
  }
  final children = <String, List<TlConstructor>>{for (final n in abstractDocs.keys) n: []};
  final standalone = <TlConstructor>[];
  for (final o in schema.objects) {
    if (_cap(o.name) == o.result) {
      if (abstractDocs.containsKey(o.result)) {
        throw StateError('${o.name} is both a constructor and an abstract class');
      }
      standalone.add(o);
    } else {
      children[o.result]!.add(o);
    }
  }

  final files = <String, String>{};
  void put(String path, String content) {
    if (files.containsKey(path)) throw StateError('Two types generate $path');
    files[path] = content;
  }

  for (final MapEntry(key: name, value: doc) in abstractDocs.entries) {
    final parts = [
      _abstractClass(name, doc, children[name]!),
      for (final c in children[name]!) _objectClass(c, className(name)),
    ];
    put('objects/${fileName(name)}.dart', "${_header}part of '../tdapi.dart';\n\n${parts.join('\n')}");
  }
  for (final o in standalone) {
    put('objects/${fileName(o.name)}.dart', "${_header}part of '../tdapi.dart';\n\n${_objectClass(o, 'TdObject')}");
  }
  for (final f in schema.functions) {
    put('functions/${fileName(f.name)}.dart', "${_header}part of '../tdapi.dart';\n\n${_functionClass(f)}");
  }

  final parts = files.keys.toList();
  put('object.dart', '$_header$_objectBase');
  put('helpers.dart', '$_header$_helpers');
  put(
    'version.dart',
    "${_header}part of 'tdapi.dart';\n\n"
        '/// TDLib release this API was generated from; libtdjson.so must be the same build.\n'
        "const String tdlibVersion = '${version.version}';\n\n"
        "const String tdlibCommit = '${version.commit}';\n",
  );

  final lib = StringBuffer(_header)
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'dart:convert' show json, jsonEncode;")
    ..writeln()
    ..writeln("part 'object.dart';")
    ..writeln("part 'helpers.dart';")
    ..writeln("part 'version.dart';");
  for (final p in parts) {
    lib.writeln("part '$p';");
  }
  lib
    ..writeln()
    ..writeln('/// Parses one TDLib JSON object; null when this schema has no such type.')
    ..writeln("TdObject? convertMapToObject(Map<String, dynamic> map) => switch (map['@type']) {");
  for (final o in schema.objects) {
    final name = className(o.name);
    lib.writeln('  $name.defaultObjectId => $name.fromJson(map),');
  }
  lib
    ..writeln('  _ => null,')
    ..writeln('};')
    ..writeln()
    ..writeln('/// Parses one TDLib JSON string; see [convertMapToObject].')
    ..writeln('TdObject? convertJsonToObject(String? query) =>')
    ..writeln('    query == null ? null : convertMapToObject(json.decode(query) as Map<String, dynamic>);');
  put('tdapi.dart', lib.toString());
  return files;
}
