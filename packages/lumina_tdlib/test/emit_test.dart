import 'package:test/test.dart';

import '../tool/src/emit.dart';
import '../tool/src/tl.dart';

const _sample = '''
//@description An error @code Error code @message Error message
error code:int32 message:string = Error;

//@class AuthorizationState @description Represents the current authorization state

//@description TDLib is ready
authorizationStateReady = AuthorizationState;

//@description A bot <b>
//@id Identifier
//@param_description Bot description; may be null
//@rows Keyboard rows
//@extra Extra data
botInfo id:int64 description:formattedText rows:vector<vector<keyboardButton>> extra:string = BotInfo;

//@description List @total_count Total @messages List of messages; messages may be null
messages total_count:int32 messages:vector<message> = Messages;

---functions---

//@description Returns the current user
getMe = User;

//@description Sends @chat_id Chat @reply_to Reply; pass null if none
sendIt chat_id:int53 reply_to:InputMessageReplyTo = Message;
''';

void main() {
  final files = emitLibrary(parseTl(_sample), const TdlibVersion('1.8.69', 'abc'));

  test('names', () {
    expect(className('error'), 'TdError');
    expect(className('formattedText'), 'FormattedText');
    expect(fieldName('is_outgoing'), 'isOutgoing');
    expect(fieldName('extra'), 'extraValue');
    expect(() => fieldName('to_json'), throwsStateError);
    expect(() => fieldName('default'), throwsStateError);
    expect(fileName('AuthorizationState'), 'authorization_state');
    expect(fileName('formattedText'), 'formatted_text');
  });

  test('file layout', () {
    expect(
      files.keys,
      containsAll([
        'tdapi.dart',
        'object.dart',
        'helpers.dart',
        'version.dart',
        'objects/error.dart',
        'objects/authorization_state.dart',
        'objects/bot_info.dart',
        'objects/messages.dart',
        'functions/get_me.dart',
        'functions/send_it.dart',
      ]),
    );
    expect(files['tdapi.dart'], contains("part 'objects/bot_info.dart';"));
    expect(files['objects/bot_info.dart'], startsWith('// GENERATED by tool/generate.dart'));
  });

  test('concrete class: types, nullability, int64, nested vectors, renamed extra', () {
    final bot = files['objects/bot_info.dart']!;
    expect(bot, contains('final class BotInfo extends TdObject {'));
    expect(bot, contains('/// A bot &lt;b&gt;'));
    expect(bot, contains('final int id;'));
    expect(bot, contains("id: _int64(json['id']),"));
    expect(bot, contains("'id': id.toString(),"));
    expect(bot, contains('final FormattedText? description;'));
    expect(bot, contains("json['description'] == null ? null : FormattedText.fromJson(_map(json['description']))"));
    expect(bot, contains("'description': description?.toJson(),"));
    expect(bot, contains('final List<List<KeyboardButton>> rows;'));
    expect(bot, contains("rows: _list(json['rows'], (e) => _list(e, (e) => KeyboardButton.fromJson(_map(e)))),"));
    expect(bot, contains("'rows': rows.map((e) => e.map((e) => e.toJson()).toList()).toList(),"));
    expect(bot, contains('final String extraValue;'));
    expect(bot, contains("'extra': extraValue,"));
    expect(bot, contains('required this.id,'));
    expect(bot, contains('    this.description,'));
  });

  test('vector with nullable elements', () {
    final m = files['objects/messages.dart']!;
    expect(m, contains('final List<Message?> messages;'));
    expect(m, contains("_list(json['messages'], (e) => e == null ? null : Message.fromJson(_map(e)))"));
    expect(m, contains("'messages': messages.map((e) => e?.toJson()).toList(),"));
  });

  test('abstract class with children in one file', () {
    final a = files['objects/authorization_state.dart']!;
    expect(a, contains('sealed class AuthorizationState extends TdObject {'));
    expect(a, contains('AuthorizationStateReady.defaultObjectId => AuthorizationStateReady.fromJson(json),'));
    expect(a, contains('final class AuthorizationStateReady extends AuthorizationState {'));
    expect(a, contains('  @override\n  AuthorizationStateReady copyWith({'));
  });

  test('functions', () {
    expect(files['functions/get_me.dart'], contains('/// Returns [User].'));
    expect(files['functions/get_me.dart'], contains('const GetMe();'));
    final send = files['functions/send_it.dart']!;
    expect(send, contains('final class SendIt extends TdFunction {'));
    expect(send, contains('final InputMessageReplyTo? replyTo;'));
    expect(send, contains("'@extra': extra,"));
  });

  test('registry and version', () {
    expect(files['tdapi.dart'], contains('BotInfo.defaultObjectId => BotInfo.fromJson(map),'));
    expect(files['tdapi.dart'], isNot(contains('GetMe.defaultObjectId')));
    expect(files['version.dart'], contains("const String tdlibVersion = '1.8.69';"));
  });

  test('a constructor that is also a declared class is rejected', () {
    const clash = '//@class Foo @description F\n\n//@description f\nfoo = Foo;\n';
    expect(() => emitLibrary(parseTl(clash), const TdlibVersion('1', 'x')), throwsStateError);
  });

  test('VERSION parsing', () {
    final v = TdlibVersion.parse('version=1.8.69\ncommit=0e88653dcbf4e44c73cb655a05b58cd749a91169\n');
    expect(v.version, '1.8.69');
    expect(() => TdlibVersion.parse('version=1.8.69\n'), throwsFormatException);
  });
}
